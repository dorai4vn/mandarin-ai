#!/usr/bin/env node
/**
 * Writes supabase/migrations/20261126000100_m2_starter_content.sql from the starter content in
 * packages/domain (D-012), so the database and the app's fallback snapshot can never drift.
 * `--check` fails if the committed file is out of date (CI).
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { STARTER_COURSE, STARTER_LEXEMES } from '../packages/domain/dist/index.js';

const OUT = new URL(
  '../supabase/migrations/20261126000100_m2_starter_content.sql',
  import.meta.url,
);
const q = (v) => (v === null || v === undefined ? 'null' : `'${String(v).replace(/'/g, "''")}'`);
const rows = (list) => list.map((r) => `  (${r.join(', ')})`).join(',\n');

const c = STARTER_COURSE;
const sql = `-- GENERATED by scripts/gen-starter-seed.mjs from packages/domain/src/content/starter.ts — do not edit.
-- Starter content (D-012). Upserts, so a re-run updates the same rows.

insert into public.lexemes (id, simplified, traditional, pinyin, meaning_vi, example, example_vi) values
${rows(STARTER_LEXEMES.map((l) => [q(l.id), q(l.simplified), q(l.traditional), q(l.pinyin), q(l.meaningVi), q(l.example), q(l.exampleVi)]))}
on conflict (id) do update set simplified = excluded.simplified, traditional = excluded.traditional,
  pinyin = excluded.pinyin, meaning_vi = excluded.meaning_vi, example = excluded.example,
  example_vi = excluded.example_vi;

insert into public.courses (id, title, level, description, provenance) values
  (${[c.id, c.title, c.level, c.description, c.provenance].map(q).join(', ')})
on conflict (id) do update set title = excluded.title, level = excluded.level,
  description = excluded.description, provenance = excluded.provenance;

insert into public.chapters (id, course_id, ordinal, title) values
${rows(c.chapters.map((ch) => [q(ch.id), q(c.id), ch.ordinal, q(ch.title)]))}
on conflict (id) do update set course_id = excluded.course_id, ordinal = excluded.ordinal, title = excluded.title;

insert into public.lessons (id, chapter_id, ordinal, title) values
${rows(c.chapters.flatMap((ch) => ch.lessons.map((l) => [q(l.id), q(ch.id), l.ordinal, q(l.title)])))}
on conflict (id) do update set chapter_id = excluded.chapter_id, ordinal = excluded.ordinal, title = excluded.title;

insert into public.lesson_lexemes (lesson_id, lexeme_id, ordinal) values
${rows(c.chapters.flatMap((ch) => ch.lessons.flatMap((l) => l.lexemeIds.map((id, i) => [q(l.id), q(id), i]))))}
on conflict (lesson_id, lexeme_id) do update set ordinal = excluded.ordinal;
`;

if (process.argv.includes('--check')) {
  let current = '';
  try {
    current = readFileSync(OUT, 'utf8');
  } catch {
    /* missing */
  }
  if (current !== sql) {
    console.error(
      'gen-starter-seed: migration is out of date — run node scripts/gen-starter-seed.mjs',
    );
    process.exit(1);
  }
  console.log('gen-starter-seed: OK');
} else {
  writeFileSync(OUT, sql);
  console.log(`gen-starter-seed: wrote ${STARTER_LEXEMES.length} lexemes`);
}
